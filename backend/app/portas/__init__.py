"""Portas: contratos que o núcleo exige do mundo de fora. Os adaptadores os implementam."""
from typing import Protocol

from app.casos_de_uso.visoes import AvaliacaoVisao, FiltroJogos, JogoVisao, Referencias
from app.dominio.entidades import Avaliacao, Jogo, Lancamento, Usuario


class RepositorioUsuario(Protocol):
    def obter_por_id(self, usuario_id: int) -> Usuario | None: ...
    def obter_por_email(self, email: str) -> Usuario | None: ...
    def salvar(self, usuario: Usuario) -> Usuario: ...


class RepositorioReferencias(Protocol):
    def todas(self) -> Referencias: ...


class RepositorioJogo(Protocol):
    def obter(self, jogo_id: int) -> Jogo | None: ...
    def existe_nome_ativo(self, nome: str, ignorar_id: int | None = None) -> bool: ...
    def salvar(self, jogo: Jogo) -> Jogo: ...
    def visao(self, jogo_id: int) -> JogoVisao | None: ...
    def listar(self, filtro: FiltroJogos) -> list[JogoVisao]: ...


class RepositorioAvaliacao(Protocol):
    def obter(self, usuario_id: int, jogo_id: int) -> Avaliacao | None: ...
    def salvar(self, avaliacao: Avaliacao) -> Avaliacao: ...
    def listar_do_jogo(self, jogo_id: int) -> list[AvaliacaoVisao]: ...


class RepositorioLancamento(Protocol):
    def listar(self) -> list[Lancamento]: ...
    def substituir_todos(self, lancamentos: list[Lancamento]) -> None: ...


class ArmazenamentoCapas(Protocol):
    def guardar(self, conteudo: bytes, extensao: str) -> str: ...
    def remover(self, nome: str) -> None: ...


class HashSenha(Protocol):
    def gerar(self, senha: str) -> str: ...
    def conferir(self, senha: str, senha_hash: str) -> bool: ...
    def simular(self, senha: str) -> None: ...  # gasta o mesmo tempo de uma conferência real


class LimitadorTentativas(Protocol):
    def bloqueado(self, chave: str) -> bool: ...
    def registrar_falha(self, chave: str) -> None: ...
    def limpar(self, chave: str) -> None: ...


class GeradorToken(Protocol):
    def gerar(self, usuario_id: int) -> str: ...
    def ler(self, token: str) -> int | None: ...


class FonteLancamentos(Protocol):
    def proximos(self) -> list[Lancamento]: ...
